function put(startTag, endTag, block, firstInsert) {
  const s = html.indexOf(startTag);
  if (s >= 0) {
    const e = html.indexOf(endTag, s) + endTag.length;
    html = html.slice(0, s) + block + html.slice(e);
  } else firstInsert();
}
put('<!-- SEO:HEAD:START', '<!-- SEO:HEAD:END -->', HEAD, () => {
  const t = /<title>[^<]*<\/title>/;
  if (!t.test(html)) throw new Error('title tag not found');
  html = html.replace(t, HEAD);
});
put('<!-- SEO:LIST:START', '<!-- SEO:LIST:END -->', LIST, () => {
  const f = '    <footer class="sf-foot">';
  if (html.indexOf(f) < 0) throw new Error('footer not found');
  html = html.replace(f, LIST + '\n\n' + f);
});
